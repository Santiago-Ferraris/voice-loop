def test_no_is_remembered_so_the_offer_is_never_repeated(build, tmp_path):
    """Being asked at every announcement is worse than the autogenerated name."""
    daemon = build(["no", "mergealo"])
    queue_stop(daemon, tmp_path)
    announce(daemon)

    assert daemon.store.get_alias("s1") is None
    assert daemon.store.alias_asked("s1") is True
    already_said = len(daemon.speaker.spoken)

    block_again(daemon, tmp_path)

    assert not any("¿La llamo" in said for said in daemon.speaker.spoken[already_said:])


