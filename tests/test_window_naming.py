"""Christening a window out loud: the offer, the answer, and never asking twice.

Claude calls an unnamed window `darwin-21`. Three of those in one repo are three
identical noises, so the first time such a window announces itself voice-loop
proposes a name — from the same request that produced the summary — and takes
one answer for it before handing the microphone to the window's own question.
"""

from __future__ import annotations

import asyncio
import json

import pytest

from voiceloop.audio import AudioUnavailable
from voiceloop.daemon import Daemon
from voiceloop.events import Event
from voiceloop.milestones import MilestoneWatcher
from voiceloop.store import Store
from voiceloop.stt.mock import MockStt
from voiceloop.summarize import Summarizer, Summary

from conftest import FakeSpeaker, write_roster
from test_reply_cycle import TTY, RecordingDelivery, StubRecorder

SLUG = "tests event processor"
SUMMARY = "terminó los tests del event processor"


class NamingSummarizer(Summarizer):
    """Answers both shapes of request without going near the network."""

    def __init__(self, summary: str = SUMMARY, slug: str = SLUG):
        super().__init__(api_key="sk-test")
        self.summary = summary
        self.slug = slug
        self.calls: list[tuple[str, str]] = []

    def _call(self, text: str) -> str:
        self.calls.append(("plain", text))
        return self.summary

    def _call_named(self, text: str) -> Summary:
        self.calls.append(("named", text))
        return Summary(text=self.summary, slug=self.slug)


@pytest.fixture
def build(config, tmp_path):
    roster = tmp_path / "sessions"
    roster.mkdir()
    made: list[Daemon] = []

    def factory(
        replies, *, name="darwin-21", cwd="/tmp/projects/darwin", heads_up="dámelo", **kwargs
    ):
        write_roster(roster, sessionId="s1", name=name, cwd=cwd, kind="interactive")
        subject = Daemon(
            config,
            store=Store(tmp_path / f"queue{len(made)}.db"),
            speaker=FakeSpeaker(),
            summarizer=kwargs.pop("summarizer", None) or NamingSummarizer(),
            watcher=MilestoneWatcher(),
            roster_dir=roster,
            recorder=kwargs.pop("recorder", None) or StubRecorder(),
            # An announcement is a heads-up now — a name and a four-second mic.
            # Everything below is about what happens *after* "dámelo", so the
            # word that asks for it is prepended once, here.
            stt=MockStt(
                replies=([heads_up] if heads_up else []) + list(replies), confidence=0.99
            ),
            delivery=RecordingDelivery(),
            **kwargs,
        )
        subject.roster_path = roster
        made.append(subject)
        return subject

    try:
        yield factory
    finally:
        for subject in made:
            subject.store.close()


def transcript(tmp_path, name: str, tail: str = "Pasaron los tests. ¿Lo mergeo?") -> str:
    path = tmp_path / f"{name}.jsonl"
    path.write_text(
        json.dumps(
            {
                "type": "assistant",
                "isSidechain": False,
                "message": {"role": "assistant", "content": [{"type": "text", "text": tail}]},
            }
        )
        + "\n",
        encoding="utf-8",
    )
    return str(path)


def queue_stop(daemon: Daemon, tmp_path, *, session="s1", name="t") -> str:
    event = Event.new(
        "stop", session, tty=TTY, transcript_path=transcript(tmp_path, name), payload={}
    )
    daemon.store.ingest(event)
    return event.id


def announce(daemon: Daemon) -> None:
    asyncio.run(daemon.announce_next())


def block_again(daemon: Daemon, tmp_path, name: str = "b", *, then=("mergealo",)) -> None:
    """The same window blocks a second time — a supersede, put back in the queue.

    Superseding is what really happens (one open item per session, summary
    dropped because it describes a turn that is no longer the last one); the
    requeue stands in for the announce loop reaching it again.
    """
    daemon.store.ingest(
        Event.new("stop", "s1", tty=TTY, transcript_path=transcript(tmp_path, name))
    )
    daemon.store.requeue(daemon.store.pendings()[0].id)
    daemon.stt.replies = ["dámelo", *then]
    announce(daemon)


