def test_an_autogenerated_window_is_offered_a_name(build, tmp_path):
    daemon = build(["dale"])
    queue_stop(daemon, tmp_path)

    announce(daemon)

    assert daemon.speaker.spoken[0].endswith("¿La llamo tests event processor?")


def test_the_offer_rides_the_summary_call_rather_than_a_second_one(build, tmp_path):
    daemon = build(["dale"])
    queue_stop(daemon, tmp_path)

    announce(daemon)

    assert [kind for kind, _ in daemon.summarizer.calls] == ["named"]


def test_a_window_you_named_yourself_is_never_second_guessed(build, tmp_path):
    """A name in Claude's prompt box is the name; nothing here improves on it."""
